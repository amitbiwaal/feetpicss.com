import type { Metadata } from "next";
import { SITE, absoluteUrl } from "./site";

type PageMeta = {
  /** Page title without the brand suffix; the root layout template appends " | FeetPicss". */
  title: string;
  description: string;
  /** Canonical path, starting with "/". */
  path: string;
  /** Use the title exactly as given instead of applying the template. */
  absoluteTitle?: boolean;
  type?: "website" | "article";
  /** Social sharing image. Defaults to the site-wide Open Graph image. */
  image?: { url: string; width: number; height: number; alt: string };
  publishedTime?: string;
  modifiedTime?: string;
  authors?: string[];
  tags?: string[];
};

export const RSS_ALTERNATE = {
  "application/rss+xml": [{ url: "/feed.xml", title: `${SITE.name} Blog` }],
};

export const ROBOTS_INDEX: NonNullable<Metadata["robots"]> = {
  index: true,
  follow: true,
  googleBot: { index: true, follow: true, "max-image-preview": "large", "max-snippet": -1, "max-video-preview": -1 },
};

export const ROBOTS_NOINDEX: NonNullable<Metadata["robots"]> = { index: false, follow: true };

/** Generated by app/opengraph-image.tsx. */
export const DEFAULT_SHARE_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: "FeetPicss — your free guide to selling feet pics online safely and anonymously",
};

/**
 * Builds the complete metadata for one page. Next.js merges metadata shallowly: a page that sets
 * `openGraph` or `alternates` replaces the whole inherited object (including the share image and
 * the RSS link), so every field is produced here to keep canonical, Open Graph and Twitter tags complete.
 */
export function pageMetadata(page: PageMeta): Metadata {
  const fullTitle = page.absoluteTitle ? page.title : `${page.title} | ${SITE.name}`;
  const source = page.image ?? DEFAULT_SHARE_IMAGE;
  const image = { ...source, url: absoluteUrl(source.url) };

  return {
    title: page.absoluteTitle ? { absolute: page.title } : page.title,
    description: page.description,
    alternates: { canonical: page.path, types: RSS_ALTERNATE },
    robots: ROBOTS_INDEX,
    openGraph: {
      type: page.type ?? "website",
      siteName: SITE.name,
      locale: SITE.locale,
      url: page.path,
      title: fullTitle,
      description: page.description,
      images: [image],
      ...(page.type === "article"
        ? {
            publishedTime: page.publishedTime,
            modifiedTime: page.modifiedTime,
            authors: page.authors,
            tags: page.tags,
          }
        : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description: page.description,
      images: [{ url: image.url, alt: image.alt }],
    },
  };
}
